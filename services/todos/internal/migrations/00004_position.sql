-- A todo's place in the list, which the user sets (docs/plan.md §8.2 todos-position, decision 118).
-- The list shows the highest position first. The todos stored before it keep their order, newest
-- first, and a new todo takes the next number of the column's sequence, so it goes on top: a move
-- never raises a position past the highest. Adding the column numbers the todos in the order they
-- lie on disk, so the UPDATE gives each todo whose number isn't its ID its ID, and setval leaves
-- an empty table's sequence alone.

-- +goose Up
ALTER TABLE todos ADD COLUMN position bigint GENERATED BY DEFAULT AS IDENTITY;
UPDATE todos SET position = id WHERE position <> id;
SELECT setval(pg_get_serial_sequence('todos', 'position'), max(position)) FROM todos;

-- +goose Down
ALTER TABLE todos DROP COLUMN position;
